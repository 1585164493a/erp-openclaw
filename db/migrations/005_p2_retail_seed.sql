-- ------------------------------------------------------------
-- 4) 日销：按商品重建 30 天，保留确定性异常注入
--    基线 15~25；product_id % 11 = 0 → 归零(断货)；product_id % 7 = 0 → ×5(促销)
--    库位直接由 product_id 决定（不依赖 inventory，避免循环依赖）
-- ------------------------------------------------------------
DELETE FROM `sales_daily`;
INSERT INTO `sales_daily` (`product_id`,`warehouse_location`,`sales_date`,`quantity`,`amount`)
WITH RECURSIVE `days` (`n`) AS (
    SELECT 0 UNION ALL SELECT `n` + 1 FROM `days` WHERE `n` < 29
),
`base` AS (
    SELECT
        p.`id`                                          AS product_id,
        ELT(1 + (p.`id` % 6), '华东DC-上海', '华南DC-广州', '华北DC-天津',
            '华中DC-武汉', '西南DC-成都', '东北DC-沈阳')   AS wh,
        COALESCE(p.`suggested_retail_price`, 0)         AS unit_price,
        d.`n`                                           AS n,
        -- 商品间规模差异（0~59）+ 商品内日间波动（0~6）→ 日销 10~75，各商品均值不同。
        -- 波动刻意压在均值之下（保底 10，波动≤6），保证 min > avg*0.5 且 max < avg*2.5，
        -- 这样异常检测【只会命中注入的异常】，不会把正常低点/高点误报，也不需要调阈值。
        -- ⚠️ 乘数 5 与模数 7 必须互质 —— 写成 (n*7)%7 会恒等于 0，波动静默失效。
        10 + ((p.`id` * 29) % 60) + ((d.`n` * 5) % 7)   AS base_qty
    FROM `product` p
    CROSS JOIN `days` d
    WHERE p.`deleted` = 0
),
`calc` AS (
    SELECT `product_id`, `wh`, `unit_price`, `n`,
        CASE
            WHEN `product_id` % 11 = 0 AND `n` BETWEEN 3 AND 6   THEN 0
            WHEN `product_id` % 7  = 0 AND `n` BETWEEN 10 AND 12 THEN `base_qty` * 5
            ELSE `base_qty`
        END AS qty
    FROM `base`
)
SELECT `product_id`, `wh`, DATE_SUB(CURDATE(), INTERVAL `n` DAY), `qty`, ROUND(`qty` * `unit_price`, 2)
FROM `calc`;

-- ------------------------------------------------------------
-- 5) 多供应商报价（比价）：给 id % 6 = 1 的 12 个 SKU 各配 3 家报价
--    报价围绕采购价上下浮动，最低价故意不总是主供应商（供比价分析演示）
-- ------------------------------------------------------------
DELETE FROM `product_supplier`;
INSERT INTO `product_supplier` (`product_id`,`supplier_id`,`quote_price`,`is_primary`,`lead_days`,`moq`,`valid_from`,`valid_to`,`remark`,`deleted`,`create_time`,`update_time`)
SELECT
    p.`id`,
    1 + ((p.`id` * 5 + k.`n` * 7) % 33),
    ROUND(p.`purchase_price` * (0.90 + k.`n` * 0.06), 2),
    IF(k.`n` = 1, 1, 0),
    5 + ((p.`id` + k.`n` * 3) % 10),
    10 * (1 + ((p.`id` + k.`n`) % 5)),
    '2026-01-01',
    NULL,
    'P2 零售主题重建',
    0, NOW(), NOW()
FROM `product` p
JOIN (SELECT 1 AS `n` UNION ALL SELECT 2 UNION ALL SELECT 3) k
WHERE p.`deleted` = 0 AND p.`id` % 6 = 1;

-- ------------------------------------------------------------
-- 6) 库存：库存量由「实际日均销量 × 目标可售天数」推导 —— 与销量自洽
--    安全库存 = 7 天用量，因此三档可售天数直接映射到预警状态：
--      · product_id % 11 = 0 → 可售 1~3 天  → 低于安全库存【紧急】
--        刻意与 §4 的「断货 4 天」是同一批商品：数据故事自洽（库存耗尽 → 断货）
--      · product_id % 9  = 3 → 可售 8~12 天 → 不预警但【偏低】
--      · 其余               → 可售 20~80 天 → 【充足】
-- ------------------------------------------------------------
DELETE FROM `inventory`;
INSERT INTO `inventory` (`product_id`,`current_quantity`,`safety_stock`,`last_inbound_time`,`last_outbound_time`,`warehouse_location`,`deleted`,`create_time`,`update_time`)
SELECT
    p.`id`,
    GREATEST(5, ROUND(COALESCE(s.avg_daily, 1) *
        (CASE WHEN p.`id` % 11 = 0 THEN 1 + (p.`id` % 3)
              WHEN p.`id` % 9  = 3 THEN 8 + (p.`id` % 5)
              ELSE 20 + (p.`id` % 61) END))),
    GREATEST(10, ROUND(COALESCE(s.avg_daily, 1) * 7)),
    DATE_SUB(NOW(), INTERVAL ((p.`id` * 11) % 60) DAY),
    DATE_SUB(NOW(), INTERVAL ((p.`id` * 5) % 20) DAY),
    ELT(1 + (p.`id` % 6), '华东DC-上海', '华南DC-广州', '华北DC-天津',
        '华中DC-武汉', '西南DC-成都', '东北DC-沈阳'),
    0, NOW(), NOW()
FROM `product` p
LEFT JOIN (
    SELECT `product_id`, AVG(`quantity`) AS avg_daily
    FROM `sales_daily` GROUP BY `product_id`
) s ON s.`product_id` = p.`id`
WHERE p.`deleted` = 0;

-- ------------------------------------------------------------
-- 7) 让存量采购单与新商品价格自洽
--    单价按新商品采购价回填（按商品 id 加一点确定性的批次差异），
--    order_detail.subtotal 是生成列会自动重算，再重算单据总额。
-- ------------------------------------------------------------
UPDATE `order_detail` od
JOIN `product` p ON p.`id` = od.`product_id`
SET od.`unit_price` = ROUND(p.`purchase_price` * (1 + ((od.`id` % 7) - 3) * 0.01), 2),
    od.`update_time` = NOW()
WHERE od.`deleted` = 0;

UPDATE `purchase_order` po
JOIN (
    SELECT `order_id`, SUM(`subtotal`) AS total
    FROM `order_detail` WHERE `deleted` = 0 GROUP BY `order_id`
) t ON t.`order_id` = po.`id`
SET po.`total_amount` = ROUND(t.`total`, 2), po.`update_time` = NOW();

